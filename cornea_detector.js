/**
 * AI Ocular ROI Auto-Detection Engine
 * Automatically detects the Left Eye (OS) and Right Eye (OD) regions
 * and extracts corneal apex biomarkers without requiring user intervention.
 */
function detectCorneaAndEyeRegionsAI(data, width, height, rgbToTemp) {
  const w = width || 320;
  const h = height || 240;

  // 1. Subsample thermal landscape (80x60 grid, step=4)
  const gw = 80;
  const gh = 60;
  const tGrid = new Float32Array(gh * gw);

  for (let gy = 0; gy < gh; gy++) {
    const py = gy * 4;
    for (let gx = 0; gx < gw; gx++) {
      const px = gx * 4;
      const idx = (py * w + px) * 4;
      tGrid[gy * gw + gx] = rgbToTemp(data[idx], data[idx + 1], data[idx + 2]);
    }
  }

  // 2. Anatomical Medial Canthi (inner eye corners / tear ducts) detection:
  // In facial thermography, the medial canthi are the prominent warm peaks bordering the nasal bridge.
  // Right Eye medial canthus: gx in 26..37 (x: 104..148), gy in 22..44 (y: 88..176)
  let reMaxT = -999, reCanthusGx = 32, reCanthusGy = 32;
  for (let gy = 22; gy <= 44; gy++) {
    for (let gx = 26; gx <= 37; gx++) {
      const t = tGrid[gy * gw + gx];
      if (t > reMaxT) {
        reMaxT = t;
        reCanthusGx = gx;
        reCanthusGy = gy;
      }
    }
  }

  // Left Eye medial canthus: gx in 38..48 (x: 152..192), gy in 22..44 (y: 88..176)
  let leMaxT = -999, leCanthusGx = 41, leCanthusGy = 32;
  for (let gy = 22; gy <= 44; gy++) {
    for (let gx = 38; gx <= 48; gx++) {
      const t = tGrid[gy * gw + gx];
      if (t > leMaxT) {
        leMaxT = t;
        leCanthusGx = gx;
        leCanthusGy = gy;
      }
    }
  }

  const reCanthusX = reCanthusGx * 4;
  const reCanthusY = reCanthusGy * 4;
  const leCanthusX = leCanthusGx * 4;
  const leCanthusY = leCanthusGy * 4;

  // Patient vertical eye level and facial midline
  const yEye = Math.round((reCanthusY + leCanthusY) / 2);
  const xMid = (reCanthusX + leCanthusX) / 2;

  const rx = 13; // Minimized compact corneal horizontal radius strictly focusing on cornea
  const ry = 11; // Minimized compact corneal vertical radius strictly focusing on cornea

  // Evaluate candidate cornea center (cx, cy)
  function evaluateCorneaAt(cx, cy, isRE) {
    let sumCC = 0, countCC = 0;
    let sumAll = 0, countAll = 0;
    let coldSpots = 0;
    let sumNC = 0, countNC = 0;
    let sumTC = 0, countTC = 0;

    const yStart = Math.max(0, cy - ry);
    const yEnd = Math.min(h - 1, cy + ry);
    const xStart = Math.max(0, cx - rx);
    const xEnd = Math.min(w - 1, cx + rx);

    for (let y = yStart; y <= yEnd; y++) {
      for (let x = xStart; x <= xEnd; x++) {
        const edist = ((x - cx) / rx) ** 2 + ((y - cy) / ry) ** 2;
        if (edist <= 1.0) {
          const idx = (y * w + x) * 4;
          const t = rgbToTemp(data[idx], data[idx + 1], data[idx + 2]);
          sumAll += t;
          countAll++;
          if (t < 34.2) coldSpots++;
          if (edist <= 0.15) {
            sumCC += t;
            countCC++;
          }
          if (isRE) {
            if (x > cx + 6 && Math.abs(y - cy) <= 8) { sumNC += t; countNC++; }
            else if (x < cx - 6 && Math.abs(y - cy) <= 8) { sumTC += t; countTC++; }
          } else {
            if (x < cx - 6 && Math.abs(y - cy) <= 8) { sumNC += t; countNC++; }
            else if (x > cx + 6 && Math.abs(y - cy) <= 8) { sumTC += t; countTC++; }
          }
        }
      }
    }

    const t_cc = countCC ? (sumCC / countCC) : 34.5;
    const t_mean = countAll ? (sumAll / countAll) : 34.5;
    const cold_ratio = countAll ? (coldSpots / countAll) : 0;
    const t_nc = countNC ? (sumNC / countNC) : t_cc + 0.35;
    const t_tc = countTC ? (sumTC / countTC) : t_cc - 0.25;
    return { t_cc, t_mean, cold_ratio, t_nc, t_tc };
  }

  // 3. Search and optimize Right Eye (OD) Cornea Center:
  // Expected position is lateral from medial canthus: x around reCanthusX - 42 to xMid - 50
  let bestOdCx = Math.max(50, Math.min(135, Math.round(xMid - 50)));
  let bestOdCy = yEye;
  let bestOdScore = -9999;
  const odXMin = Math.max(50, Math.round(xMid - 68));
  const odXMax = Math.min(135, Math.round(xMid - 34));
  const odYMin = Math.max(85, yEye - 12);
  const odYMax = Math.min(190, yEye + 12);

  for (let cy = odYMin; cy <= odYMax; cy += 2) {
    for (let cx = odXMin; cx <= odXMax; cx += 2) {
      const m = evaluateCorneaAt(cx, cy, true);
      if (m.t_cc >= 31.0 && m.t_cc <= 36.5) {
        const distPenalty = (cx - (xMid - 48)) ** 2 * 0.005 + (cy - yEye) ** 2 * 0.015;
        const tempScore = -Math.abs(m.t_cc - 34.8) * 1.0;
        const score = tempScore - distPenalty;
        if (score > bestOdScore) {
          bestOdScore = score;
          bestOdCx = cx;
          bestOdCy = cy;
        }
      }
    }
  }

  // 4. Search and optimize Left Eye (OS) Cornea Center:
  // Mirrored from sagittal midline by bilateral facial symmetry
  const expOsCx = Math.round(xMid + (xMid - bestOdCx));
  let bestOsCx = expOsCx;
  let bestOsCy = bestOdCy;
  let bestOsScore = -9999;
  const osXMin = Math.max(180, Math.round(xMid + 34));
  const osXMax = Math.min(270, Math.round(xMid + 72));
  const osYMin = Math.max(85, yEye - 12);
  const osYMax = Math.min(190, yEye + 12);

  for (let cy = osYMin; cy <= osYMax; cy += 2) {
    for (let cx = osXMin; cx <= osXMax; cx += 2) {
      const m = evaluateCorneaAt(cx, cy, false);
      if (m.t_cc >= 31.0 && m.t_cc <= 36.6) {
        const symmPenalty = (cx - expOsCx) ** 2 * 0.006 + (cy - bestOdCy) ** 2 * 0.02;
        const tempScore = -Math.abs(m.t_cc - 34.4) * 0.8;
        const score = tempScore - symmPenalty;
        if (score > bestOsScore) {
          bestOsScore = score;
          bestOsCx = cx;
          bestOsCy = cy;
        }
      }
    }
  }

  // 5. Construct full biophysical biomarkers and eye region bounding boxes
  const eyeW = 38; // Palpebral fissure half-width (bounding box width = 76px)
  const eyeH = 28; // Palpebral fissure half-height (bounding box height = 56px)

  function extractCorneaBiomarkers(cx, cy, isRE) {
    const corneaTemps = [];
    const ccTemps = [];
    const ncTemps = [];
    const tcTemps = [];
    const coldPixels = [];

    const yStart = Math.max(0, cy - ry);
    const yEnd = Math.min(h - 1, cy + ry);
    const xStart = Math.max(0, cx - rx);
    const xEnd = Math.min(w - 1, cx + rx);

    for (let y = yStart; y <= yEnd; y++) {
      for (let x = xStart; x <= xEnd; x++) {
        const edist = ((x - cx) / rx) ** 2 + ((y - cy) / ry) ** 2;
        if (edist <= 1.0) {
          const idx = (y * w + x) * 4;
          const t = rgbToTemp(data[idx], data[idx + 1], data[idx + 2]);
          corneaTemps.push(t);

          if (t < 34.2) coldPixels.push({ x, y, t });
          if (edist <= 0.15) ccTemps.push(t);

          if (isRE) {
            if (x > cx + 6 && Math.abs(y - cy) <= 8) ncTemps.push(t);
            else if (x < cx - 6 && Math.abs(y - cy) <= 8) tcTemps.push(t);
          } else {
            if (x < cx - 6 && Math.abs(y - cy) <= 8) ncTemps.push(t);
            else if (x > cx + 6 && Math.abs(y - cy) <= 8) tcTemps.push(t);
          }
        }
      }
    }

    const mean = (arr) => arr.reduce((a, b) => a + b, 0) / (arr.length || 1);
    const std = (arr, m) => Math.sqrt(arr.reduce((a, b) => a + (b - m) * (b - m), 0) / (arr.length || 1));

    const tMean = corneaTemps.length ? mean(corneaTemps) : 34.8;
    const tCC = ccTemps.length ? mean(ccTemps) : tMean;
    const tNC = ncTemps.length ? mean(ncTemps) : tCC + 0.35;
    const tTC = tcTemps.length ? mean(tcTemps) : tCC - 0.25;
    const tStd = std(corneaTemps, tMean);
    const coldRatio = coldPixels.length / (corneaTemps.length || 1);

    return {
      t_cc: parseFloat(tCC.toFixed(2)),
      t_nc: parseFloat(tNC.toFixed(2)),
      t_tc: parseFloat(tTC.toFixed(2)),
      t_mean: parseFloat(tMean.toFixed(2)),
      t_std: parseFloat(tStd.toFixed(2)),
      cold_spots_ratio: parseFloat(coldRatio.toFixed(3)),
      cold_pixels: coldPixels,
      cx: cx,
      cy: cy,
      aiCx: cx,
      aiCy: cy,
      rx: rx,
      ry: ry,
      xMin: Math.max(0, cx - eyeW),
      xMax: Math.min(w, cx + eyeW),
      yMin: Math.max(0, cy - eyeH),
      yMax: Math.min(h, cy + eyeH),
      isUserFixed: false,
      isAIDetected: true
    };
  }

  return {
    re: extractCorneaBiomarkers(bestOdCx, bestOdCy, true),
    le: extractCorneaBiomarkers(bestOsCx, bestOsCy, false)
  };
}

